// GOLDEN (M8 WP C "done when"): the Claude spawn env must be identical to pre-M8.
// anthropic.golden.json was generated by running main's applyAgentAuth (pre-WP-C
// auth-preflight.ts) over these inputs; each is replayed through the v1 shim
// (exactly what a previous-release api sends) AND as a v2 payload.
const golden = JSON.parse(readFileSync(new URL('./anthropic.golden.json', import.meta.url), 'utf8')) as {
  base: NodeJS.ProcessEnv; cases: Array<{ auth: { mode: string; apiKey?: string; oauthToken?: string }; env: NodeJS.ProcessEnv }>;
};
for (const { auth, env } of golden.cases) {
  test(`golden anthropic env: ${JSON.stringify(auth)}`, () => {
    const v1 = runAuthSchema.parse(auth);
    assert.deepEqual({ ...applyAuth(golden.base, v1) }, env, 'v1-shaped auth (previous-release api)');
    const credential = auth.mode === 'oauth-token' ? auth.oauthToken : auth.mode === 'api-key' ? auth.apiKey : undefined;
    const v2: RunAuth = { providerKind: 'anthropic', mode: auth.mode, ...(credential ? { credential } : {}) };
    assert.deepEqual({ ...applyAuth(golden.base, v2) }, env, 'v2 auth (this release)');
  });
}

const strays = {
  ANTHROPIC_API_KEY: 'S1', CLAUDE_CODE_OAUTH_TOKEN: 'S2', ANTHROPIC_AUTH_TOKEN: 'S3',
  OPENAI_API_KEY: 'S4', CODEX_API_KEY: 'S5', OPENAI_COMPAT_API_KEY: 'S6',
  COPILOT_GITHUB_TOKEN: 'S7', GH_TOKEN: 'S8', GITHUB_COPILOT_TOKEN: 'S9', PATH: '/usr/bin',
} as NodeJS.ProcessEnv;

test('every translator strips ALL its provider credentials, then sets only the mode\'s one', () => {
  const cases: Array<[RunAuth, Record<string, string | undefined>]> = [
    [{ providerKind: 'openai', mode: 'api-key', credential: 'CTX' }, { CODEX_API_KEY: 'CTX', OPENAI_API_KEY: 'CTX' }],
    [{ providerKind: 'openai', mode: 'chatgpt' }, { CODEX_API_KEY: undefined, OPENAI_API_KEY: undefined }],
    [{ providerKind: 'openai-compatible', mode: 'api-key', credential: 'CTX', baseUrl: 'http://llm:8080/v1' }, { OPENAI_COMPAT_API_KEY: 'CTX', OPENAI_COMPAT_BASE_URL: 'http://llm:8080/v1' }],
    [{ providerKind: 'openai-compatible', mode: 'none', baseUrl: 'http://llm:8080/v1' }, { OPENAI_COMPAT_API_KEY: undefined }],
    [{ providerKind: 'github', mode: 'gh-token', credential: 'CTX' }, { COPILOT_GITHUB_TOKEN: 'CTX', GH_TOKEN: undefined, GITHUB_COPILOT_TOKEN: undefined }],
  ];
  for (const [auth, expect] of cases) {
    const env = applyAuth(strays, auth);
    for (const k of TRANSLATORS[auth.providerKind].credentialEnv) {
      assert.ok(env[k] === undefined || env[k] === 'CTX', `${auth.providerKind}/${auth.mode}: stray ${k} stripped`);
    }
    for (const [k, v] of Object.entries(expect)) assert.equal(env[k], v, `${auth.providerKind}/${auth.mode}: ${k}`);
    assert.equal(env.PATH, '/usr/bin');
  }
});

test('an openai-compatible run can never send the worker\'s real OpenAI key to a third-party endpoint', () => {
  const env = applyAuth(strays, { providerKind: 'openai-compatible', mode: 'none', baseUrl: 'https://api.deepseek.com/v1' });
  // OPENAI_API_KEY is not this provider's credential (so not stripped by it), but it is
  // also never the variable the compat provider points a runtime at.
  assert.equal(env.OPENAI_COMPAT_API_KEY, undefined);
  assert.ok(!TRANSLATORS['openai-compatible'].credentialTarget({ providerKind: 'openai-compatible', mode: 'api-key' })?.startsWith('OPENAI_API'));
});

test('a mode whose credential is missing from the context sets nothing (fails clearly, never a stray)', () => {
  for (const auth of [
    { providerKind: 'openai', mode: 'api-key' }, { providerKind: 'openai-compatible', mode: 'api-key', baseUrl: 'x' },
    { providerKind: 'github', mode: 'gh-token' }, { providerKind: 'anthropic', mode: 'api-key' },
  ] as RunAuth[]) {
    const env = applyAuth(strays, auth);
    for (const k of TRANSLATORS[auth.providerKind].credentialEnv) assert.equal(env[k], undefined, `${auth.providerKind}: ${k}`);
  }
});

test('RunAuth schema: v1 payload is read as anthropic; v2 validates mode per provider', () => {
  assert.deepEqual(runAuthSchema.parse({ mode: 'oauth-token', oauthToken: 'T' }), { providerKind: 'anthropic', mode: 'oauth-token', oauthToken: 'T', credential: 'T' });
  assert.deepEqual(runAuthSchema.parse({ mode: 'vertex' }), { providerKind: 'anthropic', mode: 'vertex' });
  assert.throws(() => runAuthSchema.parse({ providerKind: 'openai', mode: 'oauth-token' }), /api-key \| chatgpt/);
  assert.throws(() => runAuthSchema.parse({ mode: 'magic' }), /oauth-token \| api-key \| vertex \| bedrock/);
});

test('authForRuntime picks the provider the runtime talks to; falls back to the v1 `auth` for anthropic', () => {
  const anth: RunAuth = { providerKind: 'anthropic', mode: 'oauth-token', credential: 'A' };
  const oai: RunAuth = { providerKind: 'openai', mode: 'api-key', credential: 'O' };
  assert.equal(providerFor('claude-code'), 'anthropic');
  assert.equal(providerFor('codex'), 'openai');
  assert.deepEqual(authForRuntime({ auth: anth, auths: { anthropic: anth, openai: oai } }, 'codex'), oai);
  assert.deepEqual(authForRuntime({ auth: anth, auths: {} }, 'claude-code'), anth, 'previous-release api: no map');
  assert.equal(authForRuntime({ auth: anth, auths: {} }, 'codex').mode, 'unset', 'never hands an anthropic credential to an openai runtime');
});

test('checkAuthConfig: missing credential names the setting; present-at-api defers; static problems surface', () => {
  const r = checkAuthConfig({ providerKind: 'openai', mode: 'api-key' }, {}, false);
  assert.equal(r.ok, false); assert.match((r as { reason: string }).reason, /OPENAI_API_KEY.*Settings/);
  assert.deepEqual(checkAuthConfig({ providerKind: 'github', mode: 'gh-token' }, {}, true), { ok: true, deferred: true });
  assert.deepEqual(checkAuthConfig({ providerKind: 'openai', mode: 'chatgpt' }, {}, false), { ok: true, deferred: false });
  assert.match((checkAuthConfig({ providerKind: 'openai-compatible', mode: 'none' }, {}, true) as { reason: string }).reason, /OPENAI_COMPAT_BASE_URL/);
  assert.match((checkAuthConfig({ providerKind: 'anthropic', mode: 'vertex' }, {}, true) as { reason: string }).reason, /ANTHROPIC_VERTEX_PROJECT_ID/);
});

test('authForTask: the task model\'s catalogue provider picks codex\'s auth; its baseUrl wins', () => {
  const anth: RunAuth = { providerKind: 'anthropic', mode: 'oauth-token', credential: 'A' };
  const oai: RunAuth = { providerKind: 'openai', mode: 'api-key', credential: 'O' };
  const compat: RunAuth = { providerKind: 'openai-compatible', mode: 'api-key', credential: 'C', baseUrl: 'http://org-wide/v1' };
  const modelCatalogExtra = {
    providers: [{ id: 'openai', kind: 'openai' }, { id: 'deepseek', kind: 'openai-compatible', baseUrl: 'https://api.deepseek.com/v1' }, { id: 'vllm', kind: 'openai-compatible' }],
    models: [
      { id: 'gpt-5.5', tier: 'max', providerId: 'openai', runtimes: ['codex'] },
      { id: 'deepseek-chat', tier: 'balanced', providerId: 'deepseek', runtimes: ['codex'] },
      { id: 'qwen-local', tier: 'fast', providerId: 'vllm', runtimes: ['codex'] },
    ],
  };
  const ctx = { auth: anth, auths: { anthropic: anth, openai: oai, 'openai-compatible': compat }, workerSettings: { maxTurns: 40, segmentTimeoutMs: 1000, modelCatalogExtra } };
  assert.deepEqual(authForTask(ctx, 'codex', 'gpt-5.5'), oai);
  assert.deepEqual(authForTask(ctx, 'codex', 'deepseek-chat'), { ...compat, baseUrl: 'https://api.deepseek.com/v1' }, 'catalogue provider baseUrl wins');
  assert.deepEqual(authForTask(ctx, 'codex', 'qwen-local'), compat, 'no provider baseUrl: the org-wide one stays');
  assert.deepEqual(authForTask(ctx, 'codex', 'unknown-model'), oai, 'unknown model: the runtime default provider');
  assert.deepEqual(authForTask(ctx, 'codex', undefined), oai);
  assert.deepEqual(authForTask(ctx, 'claude-code', 'claude-sonnet-5'), anth);
  assert.deepEqual(authForTask(ctx, 'claude-code', 'deepseek-chat'), anth, 'a runtime never switches to a provider it cannot talk to');
  assert.equal(authForTask({ auth: anth, auths: {}, workerSettings: ctx.workerSettings }, 'codex', 'deepseek-chat').mode, 'unset');
  // OpenCode (M8 WP H) talks to every provider but github; copilot always uses github.
  assert.deepEqual(authForTask(ctx, 'opencode', 'claude-sonnet-5'), anth);
  assert.deepEqual(authForTask(ctx, 'opencode', 'deepseek-chat'), { ...compat, baseUrl: 'https://api.deepseek.com/v1' });
  assert.deepEqual(authForTask(ctx, 'opencode', undefined), oai);
  assert.equal(authForTask(ctx, 'copilot', 'claude-sonnet-5').providerKind, 'github');
});

test('prepareAuthHome: chatgpt mode links CODEX_HOME/auth.json into the task home; every other case links nothing', async () => {
  const worktree = mkdtempSync(join(tmpdir(), 'asf-codex-home-'));
  const codexHome = join(worktree, 'codex-home');
  await mkdir(codexHome, { recursive: true });
  writeFileSync(join(codexHome, 'auth.json'), '{"tokens":"plan-login"}');
  process.env.CODEX_HOME = codexHome;
  try {
    const taskHome = join(worktree, 'task-1');
    await mkdir(taskHome, { recursive: true });
    await prepareAuthHome({ providerKind: 'openai', mode: 'chatgpt' }, taskHome);
    assert.ok(existsSync(join(taskHome, 'auth.json')), 'chatgpt mode links auth.json into the task home');
    assert.equal(readlinkSync(join(taskHome, 'auth.json')), join(codexHome, 'auth.json'), 'a link, not a copy, so a refreshed token is still valid for the next task');

    const apiKeyHome = join(worktree, 'task-2');
    await mkdir(apiKeyHome, { recursive: true });
    await prepareAuthHome({ providerKind: 'openai', mode: 'api-key', credential: 'K' }, apiKeyHome);
    assert.ok(!existsSync(join(apiKeyHome, 'auth.json')), 'api-key mode carries its credential in the env; nothing to link');

    const otherProviderHome = join(worktree, 'task-3');
    await mkdir(otherProviderHome, { recursive: true });
    await prepareAuthHome({ providerKind: 'anthropic', mode: 'oauth-token', credential: 'A' }, otherProviderHome);
    assert.ok(!existsSync(join(otherProviderHome, 'auth.json')), 'a non-openai provider links nothing');
  } finally {
    delete process.env.CODEX_HOME;
  }
});

test('prepareAuthHome: chatgpt mode is idempotent when the link already exists', async () => {
  const worktree = mkdtempSync(join(tmpdir(), 'asf-codex-home-'));
  const codexHome = join(worktree, 'codex-home');
  await mkdir(codexHome, { recursive: true });
  writeFileSync(join(codexHome, 'auth.json'), '{"tokens":"plan-login"}');
  process.env.CODEX_HOME = codexHome;
  try {
    const taskHome = join(worktree, 'task-1');
    await mkdir(taskHome, { recursive: true });
    await symlink(join(codexHome, 'auth.json'), join(taskHome, 'auth.json'));
    await assert.doesNotReject(prepareAuthHome({ providerKind: 'openai', mode: 'chatgpt' }, taskHome));
  } finally {
    delete process.env.CODEX_HOME;
  }
});

test('M9: anthropic vertex mode puts the auth\'s project, region and pinned models in the spawn env, over the worker env', () => {
  const auth: RunAuth = {
    providerKind: 'anthropic', mode: 'vertex',
    vertex: { projectId: 'org-proj', region: 'us-east5', defaultModel: 'claude-sonnet-5', fastModel: 'claude-haiku-4-5@20251001', maxModel: 'claude-opus-4-8' },
  };
  const workerEnv = {
    ...strays, PATH: '/usr/bin',
    ANTHROPIC_VERTEX_PROJECT_ID: 'worker-proj', CLOUD_ML_REGION: 'europe-west1', ANTHROPIC_MODEL: 'stale', ANTHROPIC_DEFAULT_OPUS_MODEL: 'stale',
  } as NodeJS.ProcessEnv;
  const env = applyAuth(workerEnv, auth);
  assert.equal(env.ANTHROPIC_VERTEX_PROJECT_ID, 'org-proj');
  assert.equal(env.CLOUD_ML_REGION, 'us-east5');
  assert.equal(env.ANTHROPIC_MODEL, 'claude-sonnet-5');
  assert.equal(env.ANTHROPIC_DEFAULT_SONNET_MODEL, 'claude-sonnet-5');
  assert.equal(env.ANTHROPIC_DEFAULT_HAIKU_MODEL, 'claude-haiku-4-5@20251001');
  assert.equal(env.ANTHROPIC_SMALL_FAST_MODEL, 'claude-haiku-4-5@20251001');
  assert.equal(env.ANTHROPIC_DEFAULT_OPUS_MODEL, 'claude-opus-4-8');
  assert.equal(env.CLAUDE_CODE_USE_VERTEX, '1');
  assert.equal(env.CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC, '1');
  assert.equal(env.ANTHROPIC_API_KEY, undefined, 'vertex strips anthropic credentials');
  assert.equal(env.PATH, '/usr/bin');
});

